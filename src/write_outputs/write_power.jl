@doc raw"""
    write_power(path::AbstractString, inputs::Dict, setup::Dict, EP::Model,
        cache::OutputCache = build_output_cache(EP, inputs, setup))

Function for writing the different values of power generated by the different technologies in operation.
The optional `cache` argument allows callers to reuse extracted model outputs across
multiple write functions to reduce memory allocations.
"""
function write_power(path::AbstractString,
    inputs::Dict,
    setup::Dict,
    EP::Model,
    cache::OutputCache = build_output_cache(EP, inputs, setup))
    gen = inputs["RESOURCES"]   # Resources (objects)
    resources = inputs["RESOURCE_NAMES"]    # Resource names
    zones = zone_id.(gen)

    G = inputs["G"]     # Number of resources (generators, storage, DR, and DERs)
    T = inputs["T"]     # Number of time steps (hours)
    
    weight = inputs["omega"]
    power = scaled_resource_time_matrix!(cache, cache.vP)

    df = DataFrame(Resource = resources,
        Zone = zones,
        AnnualSum = zeros(G))
    df.AnnualSum .= power * weight

    write_temporal_data(df, power, path, setup, "power")
    return df
end
